_last = {}      # kind -> 最近用过的句子列表（最新的在末尾），用来避免复读
RECENT_KEEP = 8  # 记住最近这么多个

# 成长层。None = 还没建（惰性建，避免每次启动都读盘）；False = 建不起来，走内置池。
# 测试可以直接把它换成临时 Lexicon，验证「长出来的句子真的被念到」。
LEXICON = None


def _lex():
    global LEXICON
    if LEXICON is None:
        try:
            import voice_lexicon
            LEXICON = voice_lexicon.default_lexicon()
        except Exception:
            LEXICON = False
    return LEXICON or None


def _pick(kind, now):
    lay = LAYERS.get(kind) or {}
    if not (lay.get("view") or lay.get("act")):
        return ""

    # 先问成长层：它会避开说过的、见底了自己补货、按反馈调权重。
    lex = _lex()
    if lex is not None:
        try:
            s = lex.pick(kind, now)
            if s:
                return s
        except Exception:
            pass                      # 成长层出任何问题都不许哑掉播报

    # 兜底：内置池。只躲开最近说过的，池子用尽就整池random。
    r = random.random()
    if r < 0.68 and lay.get("view"):
        pool = lay["view"]
    elif lay.get("act"):
        pool = lay["act"]
    else:
        pool = lay.get("view") or []
    if not pool:
        return ""
    hist = _last.get(kind) or []
    fresh = [s for s in pool if s not in hist]
    if not fresh and hist:
        fresh = [s for s in pool if s != hist[-1]]
    if not fresh:
        fresh = pool
    s = random.choice(fresh)
    hist = hist + [s]
    _last[kind] = hist[-RECENT_KEEP:]
    return s


def _tail(s):
    """态度/动作句的体检：禁词、空值。

    事实句不走这里——银行说「您尾号3307」是银行的事，不归它管。
    拿禁词去卡事实，会把整条通知吞掉（第一版就这么丢过地震预警）。
    """
    s = (s or "").strip("，。、 　")
    if not s:
        return None
    for w in FORBID:
        if w in s:
            return None
    return s


def _wrap(fact, tail=None):
    fact = (fact or "").strip("，。、 　")
    if not fact:
        return ""
    if tail:
        # 事实句自带问号/感叹号时别再补句号，否则是「工资？。」
        sep = "" if fact[-1] in "。！？!?" else "。"
        out = f"{fact}{sep}{tail}"
    else:
        out = fact
    if out[-1] not in "。！？!?":
        out += "。"
    return out


def dress(fact, kind="notice", now=None):
    """事实句 + 态度/动作。事实永远保留，态度拿不到就只念事实。

    （原先是「同类 60 秒内去重 + 12% 随机跳过」，用户嫌尾巴太少；
     现在改成每条都加，紧急仍只加半句。）
    """
    fact = (fact or "").strip("，。、 　")
    if not fact:
        return ""
    now = now or time.time()

    # 紧急：只加半句，长话短说
    if kind == "urgent":
        v = _tail(_pick("urgent", now))
        if v and len(fact) + len(v) + 1 <= TOTAL_MAX:
            return _wrap(fact, v)
        return _wrap(fact)

    s = _tail(_pick(kind, now))
    if s and len(fact) + len(s) + 1 <= TOTAL_MAX:
        return _wrap(fact, s)
    return _wrap(fact)


def dress_many(fact, kinds, now=None):
    """多条一起来的合并句。

    紧急永远优先；其余的按「第一条」定调——否则微信来文件会被
    排在上面的银行通知带成「我盯着账本」，串味。
    """
    now = now or time.time()
    if not kinds:
        return dress(fact, "notice", now=now)
    kind = "urgent" if "urgent" in kinds else kinds[0]
    return dress(fact, kind, now=now)
