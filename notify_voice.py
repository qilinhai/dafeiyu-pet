def kind_of(pkg="", title="", body="", chat_pkgs=()):
    """这条通知属于哪一类。分类决定它用什么态度说话。"""
    t = f"{title or ''}{body or ''}"
    for k, pat in RULES:
        if pat.search(t):
            return k
    if pkg and pkg in chat_pkgs:
        return "chat"
    return "notice"


